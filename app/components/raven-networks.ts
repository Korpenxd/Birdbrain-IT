type Point = readonly [number, number];
type Edge = readonly [number, number];

type Network = {
  points: readonly Point[];
  edges: readonly Edge[];
  eyeIndex: number;
};

function mesh(points: readonly Point[], maxDistance = 220, neighbours = 3): Edge[] {
  const edges = new Set<string>();

  points.forEach(([x1, y1], from) => {
    const nearest = points
      .map(([x2, y2], to) => ({ to, distance: Math.hypot(x2 - x1, y2 - y1) }))
      .filter(({ to, distance }) => to !== from && distance <= maxDistance)
      .sort((a, b) => a.distance - b.distance)
      .slice(0, neighbours);

    nearest.forEach(({ to }) => {
      const start = Math.min(from, to);
      const end = Math.max(from, to);
      edges.add(`${start}:${end}`);
    });
  });

  return Array.from(edges, (edge) => edge.split(":").map(Number) as [number, number]);
}

function network(
  bird: readonly Point[],
  eyeIndex: number,
  symbol: readonly Point[],
  symbolEdges?: readonly Edge[],
): Network {
  const symbolOffset = bird.length;
  const resolvedSymbolEdges = symbolEdges ?? mesh(symbol, 165, 3);

  return {
    points: [...bird, ...symbol],
    edges: [
      ...mesh(bird),
      ...resolvedSymbolEdges.map(([from, to]) => [from + symbolOffset, to + symbolOffset] as const),
    ],
    eyeIndex,
  };
}

